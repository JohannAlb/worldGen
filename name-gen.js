export function placeNameGen() {
  let name = determiner[Math.floor(Math.random()*determiner.length)]+" "+adjective[Math.floor(Math.random()*adjective.length)]+" "+placeNoun[Math.floor(Math.random()*placeNoun.length)]+" of "+prepNoun[Math.floor(Math.random()*prepNoun.length)];
  if (name.charAt(2) == "a") {
    name = name.slice(0, 1)+"n"+name.slice(1, name.length)
  }
  return name;
}
